/**
 * Topology specs, keyed by lab id. Rendered by components/Topology.astro with the GNS3/EVE-NG icon set.
 * Coordinates live in a 1000-wide canvas; `h` sets the canvas height.
 * Every node, port and address here comes from the lab's README and Packet Tracer topology.
 *
 * Link kinds: normal, active (primary forwarding path, animated), backup (standby, dashed),
 * serial (WAN serial), trunk (802.1Q), wireless (radio), tunnel (logical overlay such as CAPWAP).
 */
export type IconName =
  | 'router' | 'switch' | 'l3switch' | 'coreswitch' | 'root-switch' | 'pc' | 'laptop' | 'server'
  | 'wlc' | 'ap' | 'firewall' | 'internet' | 'cloud' | 'ipphone' | 'user' | 'nat' | 'vpn-router';

/** mesh: thin, light lines for dense redundant meshes; labels may sit over them (their halo masks the line). */
export type LinkKind = 'normal' | 'active' | 'backup' | 'serial' | 'trunk' | 'wireless' | 'tunnel' | 'mesh';

export interface Topology {
  h: number;
  /** When true, each node's `lp` is used exactly (no automatic side switching). */
  strictLabels?: boolean;
  zones?: { x: number; y: number; w: number; h: number; label: string; tone?: 'accent' | 'neutral' }[];
  /** lp: where the name sits relative to the icon (default below). */
  nodes: { id: string; icon: IconName; x: number; y: number; label: string; sub?: string; badge?: string; emph?: boolean; lp?: 'below' | 'above' | 'left' | 'right' }[];
  /** lt: where the link label sits along the link, 0..1 from a to b (default 0.5). */
  links: { a: string; b: string; ap?: string; bp?: string; kind?: LinkKind; label?: string; bend?: number; lt?: number }[];
  notes?: { x: number; y: number; lines: string[] }[];
  legend?: LinkKind[];
}

